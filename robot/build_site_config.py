"""Write site/config.js from .env + catalog.json.

Only PUBLIC values go into the website: the Supabase URL, the publishable key (safe to be public,
protected by Row Level Security), and the topic/ticker catalog. Never the secret key.

Run from the "Investment Center" folder:
  python robot/build_site_config.py
"""
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from analyze import load_env  # noqa: E402

ROOT = Path(__file__).parent.parent


def main():
    load_env()
    key = os.environ.get("SUPABASE_PUBLISHABLE_KEY", "")
    if not key.startswith("sb_publishable_"):
        sys.exit("SUPABASE_PUBLISHABLE_KEY missing or not a publishable key (sb_publishable_...). Refusing to write.")
    catalog = json.loads((ROOT / "robot" / "catalog.json").read_text(encoding="utf-8"))
    cfg = {
        "supabaseUrl": os.environ["SUPABASE_URL"].rstrip("/"),
        "supabaseKey": key,
        "topics": list(catalog["topics"].keys()),
        "tickers": list(catalog["tickers"].keys()),
    }
    out = ROOT / "site" / "config.js"
    out.write_text("// Generated by robot/build_site_config.py. Public values only.\nwindow.IC_CONFIG = "
                   + json.dumps(cfg, indent=2) + ";\n", encoding="utf-8")
    print(f"Wrote {out} ({len(cfg['topics'])} topics, {len(cfg['tickers'])} tickers)")


if __name__ == "__main__":
    main()
